import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const offlineDir = path.join(root, "offline");
const publicDir = path.join(root, "public");

const outFile = path.join(root, "DistroHub.html");
const rootOutFile = path.resolve(root, "..", "DistroHub.html");

function read(file) {
  return fs.readFileSync(file, "utf8");
}

function writeGenerated(name, content) {
  fs.writeFileSync(path.join(offlineDir, name), content, "utf8");
}

function mime(file) {
  if (file.endsWith(".svg")) return "image/svg+xml";
  if (file.endsWith(".png")) return "image/png";
  if (file.endsWith(".webp")) return "image/webp";
  if (file.endsWith(".jpg") || file.endsWith(".jpeg")) return "image/jpeg";
  if (file.endsWith(".woff2")) return "font/woff2";
  return "application/octet-stream";
}

function dataUri(file) {
  return `data:${mime(file)};base64,${fs.readFileSync(file).toString("base64")}`;
}

// 1. Logos: turn every distro SVG into a data URI.
const distroSource = read(path.join(root, "src", "data", "distros.ts"));
const pairRe = /slug:\s*"([^"]+)"[\s\S]*?logo:\s*"([^"]+)"/g;
const logos = {};
let pair;
while ((pair = pairRe.exec(distroSource))) {
  const [, slug, logoPath] = pair;
  const file = path.join(publicDir, logoPath.replace(/^\//, ""));
  if (fs.existsSync(file)) logos[slug] = dataUri(file);
}

writeGenerated(
  "logos.generated.ts",
  `// Generated by offline/build.mjs from public/logos.\nexport const LOGOS: Record<string, string> = ${JSON.stringify(logos, null, 2)};\n`,
);

// 2. Runtime asset map: wallpapers and icon themes.
const assets = {};
for (const dir of ["wallpapers", "icons"]) {
  const base = path.join(publicDir, dir);
  if (!fs.existsSync(base)) continue;
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) {
        walk(full);
        continue;
      }
      const url = `/${path.relative(publicDir, full).split(path.sep).join("/")}`;
      assets[url] = dataUri(full);
    }
  };
  walk(base);
}

// 3. Bundle the React app.
const jsBuild = await esbuild.build({
  entryPoints: [path.join(offlineDir, "main.tsx")],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: ["es2020"],
  jsx: "automatic",
  platform: "browser",
  define: { "process.env.NODE_ENV": '"production"' },
  alias: {
    "@": path.join(root, "src"),
    "next/link": path.join(offlineDir, "link.tsx"),
    "next/navigation": path.join(offlineDir, "navigation.tsx"),
  },
  logLevel: "warning",
});
let js = jsBuild.outputFiles[0].text;

// 4. Compile Tailwind + the shared design system, then minify.
const inputCss = read(path.join(offlineDir, "offline.css"));
const cssResult = await postcss([tailwind()]).process(inputCss, {
  from: path.join(offlineDir, "offline.css"),
  to: path.join(offlineDir, "offline.out.css"),
});
let css = cssResult.css;

// 5. Inline every local font referenced by fonts.css.
for (const fontFolder of ["fonts", "fonts2"]) {
  const fontDir = path.join(publicDir, fontFolder);
  if (!fs.existsSync(fontDir)) continue;
  css = css.replace(new RegExp(`url\\("\\/${fontFolder}\\/([^"]+)"\\)`, "g"), (match, name) => {
    const file = path.join(fontDir, name);
    return fs.existsSync(file) ? `url("${dataUri(file)}")` : match;
  });
}

const cssMin = await esbuild.transform(css, { loader: "css", minify: true });
css = cssMin.code;

// Inline scripts must not be terminated by a literal closing script tag inside data.
js = js.replace(/<\/script/gi, "<\\/script");

const favicon =
  "data:image/svg+xml," +
  encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="7" fill="#0e0e15"/><path d="M8 9h7c4.4 0 7 2.5 7 6.9S19.4 23 15 23H8V9Zm4 3.4v7.2h2.8c2.4 0 3.8-1.3 3.8-3.6s-1.4-3.6-3.8-3.6H12Z" fill="#f4f1e8"/><path d="M23.5 9v14" stroke="#ff5c38" stroke-width="1.8"/></svg>`,
  );

const html = `<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<meta name="theme-color" content="#07070b">
<title>DistroHub: каталог дистрибутивов Linux</title>
<meta name="description" content="Автономный каталог дистрибутивов Linux: подбор за 5 вопросов, сравнение, гайды, отзывы и избранное. Работает без сервера и интернета.">
<link rel="icon" href="${favicon}">
<script>
(function(){try{var t=localStorage.getItem('dh-theme');var dark=t?t==='dark':true;document.documentElement.classList.toggle('dark',dark);}catch(e){}})();
</script>
<style>${css}</style>
</head>
<body>
<div id="root"></div>
<noscript><div style="max-width:640px;margin:15vh auto;padding:24px;font-family:system-ui"><h1>DistroHub</h1><p>Для работы каталога нужен JavaScript. Включите его в настройках браузера и откройте файл снова.</p></div></noscript>
<script>globalThis.__DH_ASSETS__=${JSON.stringify(assets).replace(/</g, "\\u003c")}</script>
<script>${js}</script>
</body>
</html>
`;

fs.writeFileSync(outFile, html, "utf8");
fs.writeFileSync(rootOutFile, html, "utf8");

const size = (html.length / 1024).toFixed(0);
console.log(`DistroHub.html: ${size} KB`);
console.log(`  ${outFile}`);
console.log(`  ${rootOutFile}`);
console.log(`  logos: ${Object.keys(logos).length}, assets: ${Object.keys(assets).length}`);
